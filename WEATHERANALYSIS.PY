import pandas as pd
import matplotlib.pyplot as plt
import os
folder = os.path.dirname(os.path.abspath(__file__))
file_path = os.path.join(folder, "weather.csv")
df = pd.read_csv(file_path)
print("Weather Data:")
print(df)
average_temp = df["Temperature"].mean()
maximum_temp = df["Temperature"].max()
minimum_temp = df["Temperature"].min()
print("\n--- Temperature Analysis ---")
print(f"Average Temperature: {average_temp:.2f} °C")
print(f"Maximum Temperature: {maximum_temp} °C")
print(f"Minimum Temperature: {minimum_temp} °C")
hottest_day = df.loc[df["Temperature"].idxmax()]
print("\n--- Hottest Day ---")
print("Date:", hottest_day["Date"])
print("Temperature:", hottest_day["Temperature"], "°C")
plt.figure(figsize=(8, 5))
plt.plot(df["Date"], df["Temperature"], marker="o")
plt.title("Daily Temperature Changes")
plt.xlabel("Date")
plt.ylabel("Temperature (°C)")
plt.xticks(rotation=45)
plt.grid(True)
plt.tight_layout()
plt.show()
plt.figure(figsize=(8, 5))
plt.hist(df["Temperature"], bins=5, edgecolor="black")
plt.title("Distribution of Temperatures")
plt.xlabel("Temperature (°C)")
plt.ylabel("Frequency")
plt.tight_layout()
plt.show()
plt.figure(figsize=(8, 5))
plt.scatter(df["Humidity"], df["Temperature"])
plt.title("Humidity vs Temperature")
plt.xlabel("Humidity (%)")
plt.ylabel("Temperature (°C)")
plt.grid(True)
plt.tight_layout()
plt.show()

